#' Calculate Normalized Cosine Proximity from Speakers to a Centroid Vector
#'
#' Computes the cosine proximity (semantic similarity) between each speaker's embedding vector
#' and a target centroid vector (such as one computed with \code{\link{compute_dictionary_centroid}}).
#' By default, proximity values are normalized so that higher values indicate greater alignment
#' and semantic closeness to the concept centroid.
#'
#' @param speaker_landscape A \code{list} object returned by \code{\link{make_speaker_landscapes}},
#'   or a data frame containing an \code{author} column.
#' @param centroid A numeric vector representing the concept centroid, or an object of class
#'   \code{"dictionary_centroid"} returned by \code{\link{compute_dictionary_centroid}}.
#' @param embedding The vector embeddings object: either an object of class \code{word2vec},
#'   a numeric matrix where \code{rownames} contain the speaker identifiers, or a file path to an .emb file.
#' @param metric Character string specifying the proximity/distance metric:
#'   \code{"normalized_proximity"} (default, min-max normalized to the range 0 to 1 where 1 is maximum closeness),
#'   \code{"cosine_similarity"} (raw cosine similarity in -1 to 1), or
#'   \code{"cosine_distance"} (1 - cosine similarity).
#' @param rescale Character string specifying how to normalize cosine proximity when \code{metric = "normalized_proximity"}:
#'   \code{"minmax"} (default, linearly scales observed similarities to 0 to 1 across the speaker sample),
#'   \code{"unit"} (theoretical scaling from -1 to 1 to 0 to 1 via \code{(sim + 1) / 2}), or
#'   \code{"none"} (keeps raw cosine values).
#' @param column_name Character string specifying the name of the column in which to store
#'   the resulting proximity in the speakers table. Defaults to \code{"centroid_proximity"}.
#'
#' @return The input \code{speaker_landscape} list with \code{column_name} and \code{cosine_similarity}
#'   added to the \code{$speakers} data frame. If a data frame was passed as \code{speaker_landscape},
#'   the updated data frame is returned directly.
#'
#' @examples
#' \dontrun{
#' # Assume 'landscape' is generated by make_speaker_landscapes()
#' # and 'embedding' is trained by train_embedding_model()
#' anger_centroid <- compute_dictionary_centroid(c("anger", "rage", "fury"), embedding)
#'
#' # Compute normalized cosine proximity from each speaker to the anger centroid
#' landscape <- calculate_centroid_proximity(
#'   speaker_landscape = landscape,
#'   centroid = anger_centroid,
#'   embedding = embedding
#' )
#' head(landscape$speakers)
#' }
#' @export
calculate_centroid_proximity <- function(speaker_landscape,
                                         centroid,
                                         embedding,
                                         metric = c("normalized_proximity", "cosine_similarity", "cosine_distance"),
                                         rescale = c("minmax", "unit", "none"),
                                         column_name = "centroid_proximity") {

  metric <- match.arg(metric)
  rescale <- match.arg(rescale)

  # 1. Extract centroid vector
  if (inherits(centroid, "dictionary_centroid") || (is.list(centroid) && "centroid" %in% names(centroid))) {
    c_vec <- as.numeric(centroid$centroid)
  } else if (is.numeric(centroid)) {
    c_vec <- as.numeric(centroid)
  } else {
    stop("`centroid` must be a numeric vector or an object returned by compute_dictionary_centroid().")
  }

  # 2. Extract embedding matrix
  emb_mat <- extract_embedding_matrix(embedding)

  if (is.null(rownames(emb_mat))) {
    stop("`embedding` must have rownames corresponding to speaker/token identifiers.")
  }

  if (ncol(emb_mat) != length(c_vec)) {
    stop(sprintf(
      "Dimensionality mismatch: embedding has %d dimensions, but centroid has %d dimensions.",
      ncol(emb_mat), length(c_vec)
    ))
  }

  # 3. Extract speaker table
  is_landscape_list <- is.list(speaker_landscape) && "speakers" %in% names(speaker_landscape)
  if (is_landscape_list) {
    df_speakers <- speaker_landscape$speakers
  } else if (is.data.frame(speaker_landscape)) {
    df_speakers <- speaker_landscape
  } else {
    stop("`speaker_landscape` must be a list returned by make_speaker_landscapes() or a data frame.")
  }

  if (!"author" %in% colnames(df_speakers)) {
    stop("The speaker data does not contain an 'author' column.")
  }

  # 4. Match speakers to embedding rows
  emb_authors <- rownames(emb_mat)
  emb_authors_lower <- tolower(emb_authors)
  speaker_authors_lower <- tolower(as.character(df_speakers$author))

  match_idx <- match(speaker_authors_lower, emb_authors_lower)

  proximities <- rep(NA_real_, nrow(df_speakers))
  raw_sims <- rep(NA_real_, nrow(df_speakers))
  valid_mask <- !is.na(match_idx)

  if (any(valid_mask)) {
    matched_vecs <- emb_mat[match_idx[valid_mask], , drop = FALSE]

    # Compute raw cosine similarity
    vec_norms <- sqrt(rowSums(matched_vecs^2))
    vec_norms[vec_norms == 0] <- 1

    c_norm <- sqrt(sum(c_vec^2))
    if (c_norm == 0) c_norm <- 1

    cosine_sims <- as.vector((matched_vecs %*% c_vec) / (vec_norms * c_norm))
    raw_sims[valid_mask] <- cosine_sims

    if (metric == "normalized_proximity") {
      if (rescale == "minmax") {
        min_sim <- min(cosine_sims, na.rm = TRUE)
        max_sim <- max(cosine_sims, na.rm = TRUE)
        if (max_sim > min_sim) {
          proximities[valid_mask] <- (cosine_sims - min_sim) / (max_sim - min_sim)
        } else {
          proximities[valid_mask] <- 1.0
        }
      } else if (rescale == "unit") {
        proximities[valid_mask] <- (cosine_sims + 1) / 2
      } else {
        proximities[valid_mask] <- cosine_sims
      }
    } else if (metric == "cosine_similarity") {
      proximities[valid_mask] <- cosine_sims
    } else if (metric == "cosine_distance") {
      proximities[valid_mask] <- 1 - cosine_sims
    }
  }

  n_missing <- sum(!valid_mask)
  if (n_missing > 0) {
    message(sprintf(
      "Note: %d of %d speakers were not found in the embedding matrix.",
      n_missing, nrow(df_speakers)
    ))
  }

  # 5. Store values in speaker table
  df_speakers[[column_name]] <- proximities
  df_speakers[["cosine_similarity"]] <- raw_sims

  if (is_landscape_list) {
    speaker_landscape$speakers <- df_speakers
    return(speaker_landscape)
  } else {
    return(df_speakers)
  }
}

#' @rdname calculate_centroid_proximity
#' @export
calculate_centroid_distance <- function(speaker_landscape,
                                        centroid,
                                        embedding,
                                        metric = c("normalized_proximity", "cosine_similarity", "cosine_distance"),
                                        rescale = c("minmax", "unit", "none"),
                                        column_name = "centroid_proximity") {
  calculate_centroid_proximity(
    speaker_landscape = speaker_landscape,
    centroid = centroid,
    embedding = embedding,
    metric = metric,
    rescale = rescale,
    column_name = column_name
  )
}
